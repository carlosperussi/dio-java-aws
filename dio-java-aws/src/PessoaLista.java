public class PessoaLista {
    private String nome;
    private int idade;

    public PessoaLista(String nome, int idade) {
        this.nome = nome;
        this.idade = idade;
    }

    public PessoaLista() {
    }

    public String getNome() {
        return nome;
    }

    public void setNome(String nome) {
        this.nome = nome;
    }

    public int getIdade() {
        return idade;
    }

    public void setIdade(int idade) {
        this.idade = idade;
    }

    
    
}
