public class TiposPrimitivos {
    public static void main(String[] args) {
        // Tipos de variáveis primitivas em Java
        boolean b;
        byte by;
        short s;
        int i;
        long l;
        float f;
        double d;
        char c;

        // Tipos de classe wrapper correspondentes
        Boolean bWrapper;
        Byte byWrapper;
        Short sWrapper;
        Integer iWrapper;
        Long lWrapper;
        Float fWrapper;
        Double dWrapper;
        Character cWrapper;
    }
}
